<?php

namespace App\Http\Controllers\Auctions;

use App\Http\Controllers\Controller;
use App\Models\Auction;
use App\Models\AuctionImage;
use App\Services\Auctions\AuctionImageVariants;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Gate;
use Illuminate\Support\Facades\Storage;
use Symfony\Component\HttpFoundation\Response;

/**
 * The only way to read a listing photo. The files sit on a private disk;
 * this route applies the same rule as the auction page itself (a draft is
 * the seller's alone, a published auction is visible to signed-in users)
 * and, through scoped route binding, only serves an image under the
 * auction it belongs to.
 *
 * `?size=thumb|medium|large` picks a derived copy (see AuctionImageVariants); with no size the response is the `large`
 * copy. What leaves the server is always a re-encoded copy with no EXIF block, never the uploaded file. The copy is
 * cacheable by the viewer's browser for a month (`private`, so no shared cache keeps it) and answers a conditional request
 * with 304: its content never changes for a given photo id and size.
 */
class AuctionImageController extends Controller
{
    public function show(Request $request, Auction $auction, AuctionImage $image, AuctionImageVariants $variants): Response
    {
        Gate::authorize('view', $auction);

        $asked = $request->query('size');
        $size = is_string($asked) || $asked === null ? AuctionImageVariants::normalize($asked) : null;

        abort_if($size === null, 404);

        $disk = Storage::disk(AuctionImage::DISK);

        // The path is generated by the server, so a traversing one can only come from a tampered row; Flysystem throws on
        // it, and a photo that cannot be read is a 404, never a 500.
        try {
            $path = $variants->ensure($image, $size);
            $mime = AuctionImageVariants::format()[1];

            // No smaller copy could be made (no GD, no memory): serve the stored file as before rather than nothing.
            if ($path === null) {
                $path = $image->path;
                $mime = $image->mime;
            }

            $exists = $disk->exists($path);
        } catch (\Throwable) {
            $exists = false;
        }

        abort_unless($exists, 404);

        $etag = '"'.substr(sha1($image->getKey().'|'.$size.'|'.$path.'|'.$disk->size($path).'|'.$disk->lastModified($path)), 0, 32).'"';
        $headers = [
            'Content-Type' => $mime,
            'X-Content-Type-Options' => 'nosniff',
            'Cache-Control' => 'private, max-age=2592000',
            'ETag' => $etag,
        ];

        if (in_array($etag, $request->getETags(), true)) {
            return response('', 304, $headers);
        }

        return $disk->response($path, null, $headers, 'inline');
    }
}
